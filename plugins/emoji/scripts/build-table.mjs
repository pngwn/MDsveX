// writes src/table.ts from the gemoji package, run it after a gemoji update
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { gemoji } from 'gemoji';

const here = dirname(fileURLToPath(import.meta.url));
const { version } = createRequire(import.meta.url)('gemoji/package.json');

const NAME = /^[a-z0-9_+-]+$/;
const seen = new Set();
const lines = [];
for (const { emoji, names, description } of gemoji) {
	for (const name of names) {
		if (!NAME.test(name))
			throw new Error(`a shortcode the plugin cannot match, ${name}`);
		if (seen.has(name)) throw new Error(`a shortcode twice, ${name}`);
		seen.add(name);
	}
	if (/[\t\n`\\$]/.test(emoji + names.join('') + description)) {
		throw new Error(`a character the table cannot hold, in ${names[0]}`);
	}
	lines.push(`${emoji}\t${names.join(' ')}\t${description}`);
}

writeFileSync(
	join(here, '../src/table.ts'),
	`// generated by scripts/build-table.mjs from gemoji ${version}, do not edit

/** an emoji a line, the emoji, its shortcodes and its description, tab separated */
export const TABLE = \`${lines.join('\n')}\`;
`
);
console.log(`${lines.length} emoji, ${seen.size} shortcodes`);
