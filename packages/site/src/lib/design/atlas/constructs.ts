// every construct PFM has, one atlas entry each. The id is the entry's anchor,
// /atlas#<id>, which the PFM Reference links to, so an id never changes once it
// ships (design/atlas-anchors.md lists them).
//
// Only the words are written here. The score is the real parser's reading of
// `source`, and the output is mdsvex's real compile of it (compile.server.ts).
// The notes follow PFM.md; `code` in backticks is set as code
import type { KindName } from '../pfm';

export type Family = 'block' | 'inline' | 'svelte' | 'directive' | 'document';

/** what a construct needs from the compile beyond the atlas's plain options */
export type Needs = 'math' | 'highlight';

export interface Construct {
	id: string;
	name: string;
	family: Family;
	/** the shortest mark that stands for it, for the index */
	glyph: string;
	/** the parser kinds it reads as; the first is the construct itself and gives its colour */
	kinds: KindName[];
	/** a small real source, run through the parser and the compile */
	source: string;
	/** what it is, a sentence or two */
	what: string;
	/** the edges: where it stops being itself, and what it does there */
	edges: string[];
	/** where it parts from CommonMark, or where it comes from when CommonMark lacks it */
	commonmark: string;
	needs?: Needs[];
	related?: string[];
}

